import assert from "node:assert/strict";
import fs from "node:fs";
const read = f => fs.readFileSync(new URL(f, import.meta.url), "utf8");
const app = read("app.js");
const css = read("style.css");

assert.match(app, /const FX_KINDS=\["stars","snow","maple","rain","stars2"\]/);
assert.match(app, /function playAvatarFx\(/);
assert.match(app, /function playWeatherFx\(/);
assert.match(app, /function playStarRain\(/);
assert.match(app, /function stopAvatarFx\(/);
assert.match(app, /function fxReduced\(/);
assert.match(app, /prefers-reduced-motion:\s*reduce/);
assert.ok(app.includes('if(kind==="stars")playStarRain();else if(kind==="stars2")playStarRain2();else playWeatherFx(kind)'), "rotator plays template stars first and canvas stars as stars2");
assert.ok(app.includes('starAv.onclick=ev=>{ev.preventDefault();playAvatarFx()}'), "avatar tap uses the rotator");
assert.equal(app.includes('starAv.onclick=ev=>{ev.preventDefault();playStarRain()}'), false, "avatar no longer only plays stars");
assert.match(app, /id="nova-weather"/);
assert.match(app, /function wxFlake\(/);
assert.match(app, /function preloadMaple\(/);
assert.match(app, /const MAPLE_SRC=/);
assert.match(app, /assets\/maple\/leaf/);
assert.match(app, /ctx\.drawImage\(im/);
assert.equal(app.includes("function wxMaple("), false, "maple uses leaf sprites, not a vector path");
assert.match(app, /y:spread\?rnd\(-H\*\.2,H\):rnd\(-70,-10\)/);
assert.match(app, /vy:rnd\(36,88\)/);
assert.match(app, /amp:rnd\(16,52\)/);
assert.match(app, /1\.6\*0\.78/);
assert.match(app, /reduce\?700:10000/);
assert.match(app, /setTimeout\(stopWeatherFx,400\)/);
assert.match(app, /function playStarRain2\(/);
assert.match(app, /function stopStarRain2\(/);
assert.match(app, /function preloadStarRain2\(/);
assert.match(app, /cv\.id="nova-starrain2"/);
assert.match(app, /function starSprite2\(/);
assert.match(app, /starT2=setTimeout\(\(\)=>\{cv\.classList\.add\("out"\);starF2=setTimeout\(stopStarRain2,400\)\},reduce\?700:10000\)/);
assert.ok(app.includes('stopStarRain2()'), "weather/avatar stop also stops canvas stars");

assert.match(css, /html #nova-starrain,html #nova-starrain2,html #nova-weather\{/);
assert.match(css, /#nova-weather\{[^}]*position:fixed/);
assert.match(css, /#nova-weather\{[^}]*inset:0/);
assert.match(css, /#nova-weather\{[^}]*z-index:80/);
assert.match(css, /#nova-weather\{[^}]*pointer-events:none/);
assert.match(css, /html #nova-starrain\.out,html #nova-starrain2\.out,html #nova-weather\.out\{opacity:0\}/);
assert.match(app, /function playRainGo\(/);
assert.ok(app.includes('if(kind==="rain"){playRainGo();return}'), "rain has its own canvas painter");
assert.match(app, /const STARFALL_SRC=\["pink","champagne","gold"\]\.map\(n=>"assets\/starfall\/star-"\+n\+"\.png"\)/);
assert.match(app, /function playStarFall\(/);
assert.match(app, /cv\.id="nova-starrain"/);
assert.match(app, /starT=setTimeout\(\(\)=>\{cv\.classList\.add\("out"\);starF=setTimeout\(stopStarRain,400\)\},reduce\?700:10000\)/);
assert.equal(app.includes("starrain.gif"), false, "template stars replace the stepped GIF");
for (const n of ["pink", "champagne", "gold"]) assert.ok(fs.existsSync(new URL("assets/starfall/star-" + n + ".png", import.meta.url)), n + " star sprite exists");
console.log("avatar-fx ok");
